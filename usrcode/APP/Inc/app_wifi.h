/**
 ******************************************************************************
 * @file    app_wifi.h
 * @brief   WiFi 上报任务头文件 — ESP8266 连路由器 + TCP 上报温湿度
 *
 *  ╔══════════════════════════════════════════════════════════════╗
 *  ║  ★ 必须修改以下 4 个宏为你的实际环境，否则无法连网 ★         ║
 *  ╠══════════════════════════════════════════════════════════════╣
 *  ║  WIFI_SSID        : 你的 2.4GHz WiFi 名称                    ║
 *  ║  WIFI_PASSWORD    : WiFi 密码                                ║
 *  ║  TCP_SERVER_IP    : 电脑/手机的局域网 IP（同一网段）          ║
 *  ║  TCP_SERVER_PORT  : 电脑/手机网络调试助手监听的端口           ║
 *  ╚══════════════════════════════════════════════════════════════╝
 *
 *  任务流程：
 *    1. 初始化 ESP8266 → AT 测试 → 设 STA 模式 → 连 WiFi → 获取 IP
 *    2. 连接 TCP 服务器
 *    3. 周期读取 DHT11 共享快照 → 格式化字符串 → TCP 发送
 *    4. 发送失败或断线时自动重连（WiFi + TCP）
 *
 *  上报数据格式（纯文本，便于网络调试助手直接查看）：
 *    [DHT11] Temp=25.5 C | Hum=60.0 %
 ******************************************************************************
 */
#ifndef APP_WIFI_H
#define APP_WIFI_H

#include <stdint.h>

/* ==========================================================================
 *  ★ 用户配置区 —— 请根据实际环境修改 ★
 * ========================================================================== */

#define WIFI_SSID           "your_wifi_ssid"      /*!< 2.4GHz WiFi 名称（区分大小写） */
#define WIFI_PASSWORD       "your_wifi_password"                  /*!< WiFi 密码（区分大小写） */

#define TCP_SERVER_IP       "192.168.168.3"     /*!< 电脑/手机局域网 IP */
#define TCP_SERVER_PORT     8080U               /*!< 网络调试助手监听端口 */

#define WIFI_REPORT_PERIOD_MS  3000U            /*!< 温湿度上报周期（毫秒），建议 >= 采集周期2000ms */


/* ==========================================================================
 *  任务参数
 * ========================================================================== */

#define WIFI_TASK_STACK_SIZE   (512U * 4U)      /*!< 任务栈大小（字节） */
#define WIFI_TASK_PRIORITY     osPriorityNormal /*!< 任务优先级 */

/* ==========================================================================
 *  API
 * ========================================================================== */

/**
 * @brief  WiFi 上报任务入口
 * @param  argument 未使用
 * @note   由 app_tasks.c 创建为 FreeRTOS 任务
 */
void APP_WIFI_Task(void *argument);

/**
 * @brief  获取WiFi/TCP连接状态
 * @retval bit0=WiFi已连接, bit1=TCP已连接
 */
uint8_t APP_WIFI_GetStatus(void);

#endif /* APP_WIFI_H */
