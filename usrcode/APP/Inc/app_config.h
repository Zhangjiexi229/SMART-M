/**
 ******************************************************************************
 * @file    app_config.h
 * @brief   告警阈值配置头文件 — 三路独立阈值 + 按键设置模式状态
 *
 *  对应工作任务 Day5「按键设置阈值」：
 *    - 三路独立阈值：温度(℃)/振动(g)/电流(A)
 *    - 设置模式状态机：正常(SET_MODE_EXIT) -> 选择(SET_MODE_SELECT)
 *                      -> 调整(SET_MODE_ADJUST) -> 确认保存
 *    - 阈值保存到 STM32 内部 Flash（Sector11），重启不丢失
 *
 *  使用方：
 *    app_alarm  （阈值比较与告警判断）
 *    app_key_matrix（按键调整阈值）
 *    app_oled   （阈值页面显示与高亮）
 ******************************************************************************
 */
#ifndef APP_CONFIG_H
#define APP_CONFIG_H

#include <stdint.h>

/* ==========================================================================
 *  阈值配置结构
 * ========================================================================== */
typedef struct {
    float temp_high;   /*!< 温度告警阈值（℃），默认 60.0 */
    float vib_high;    /*!< 振动告警阈值（g），默认 3.0 */
    float curr_high;   /*!< 电流告警阈值（A），默认 5.0 */
} ThresholdConfig_t;

/* 按键设置模式 */
typedef enum {
    SET_MODE_EXIT    = 0,   /* 正常模式 */
    SET_MODE_SELECT,        /* 选择要修改的阈值项 */
    SET_MODE_ADJUST         /* 调整数值 */
} SetMode_t;

/* ==========================================================================
 *  全局配置与状态（外部可读/可写）
 * ========================================================================== */
extern ThresholdConfig_t g_threshold;   /*!< 当前生效阈值 */
extern SetMode_t g_set_mode;            /*!< 设置模式 */
extern uint8_t g_set_selected;          /*!< 选中项：0=温度,1=振动,2=电流 */

/* ==========================================================================
 *  API
 * ========================================================================== */

/**
 * @brief  阈值配置初始化 — 从内部Flash加载，无有效配置则使用默认值
 * @note   在 APP_Init 中、调度器启动前调用
 */
void APP_CONFIG_Init(void);

/**
 * @brief  保存当前阈值到内部Flash（按键确认保存时调用，低频）
 * @retval 0=成功，非0=失败（见 bsp_flash_config 返回码）
 */
uint8_t APP_CONFIG_Save(void);

#endif /* APP_CONFIG_H */
